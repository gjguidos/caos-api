"""TEST-SAFETY-0.1: disposable Redis verification and per-run UTU isolation for tests.

Integration fixtures create, revoke and delete tenant authority state in
``UTU_TEST_REDIS_URL``. They run only inside the repository harness
(``scripts/test-harness/run.sh``), which establishes the disposable boundary: a
dedicated ``--internal`` Docker network holding only containers it created, with no
published ports, no volumes and no live configuration or credentials. Fixtures check
that boundary and that exact Redis before any destructive operation:

1. **Before any connection** (``disposable_utu_redis_url``):
   - the existing Nataraja guard (``require_disposable_redis``) refuses a missing,
     non-``redis://`` or host-less URL, and any endpoint equivalent to the application's
     configured Redis (same host/port, or the same resolved address);
   - the runner has no default route: positive evidence of the harness's internal
     network (a container that can reach other networks, such as the live API, is
     refused);
   - the harness declared the Redis process identity (``UTU_TEST_REDIS_RUN_ID``).
2. **Before any write** (``verify_disposable_redis``), connected only to the declared
   Redis: ``INFO server`` ``run_id`` (generated by that Redis process, not settable by
   clients) must equal the declaration, and no production-format authority key may
   exist (live or contaminated). A ``run_id`` alone is a process identity, not proof
   of disposability; it binds the tests to the server the harness created.
3. **Per-run isolation** (``isolate_utu``): each run's UTU store uses its own key
   prefix, bound as the ``utu_authority`` singleton's revocation store. Every UTU
   read, write, revocation and permit check goes through the store's ``_key``, so a
   run can only touch, and only deletes, its own tenant hash.

Test-only. Production key formats and UTU semantics are unchanged.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any
from uuid import uuid4

import pytest
from dependency_injector import providers

from src.base.config.config import settings
from src.domains.agentverse.nataraja.verify import (
    UnsafeVerificationTarget,
    require_disposable_redis,
)
from src.domains.agentverse.security.revocation import RedisRevocationStore

TEST_REDIS_ENV = "UTU_TEST_REDIS_URL"
# Declared by scripts/test-harness/run.sh from the Redis container it created.
TEST_REDIS_IDENTITY_ENV = "UTU_TEST_REDIS_RUN_ID"
HARNESS = "scripts/test-harness/run.sh"
_RUN_ID = re.compile(r"[0-9a-f]{40}")
_RTF_UP, _RTF_REJECT = 0x0001, 0x0200
TEST_KEY_PREFIX = "caos-test:"
# Production-format authority keys. Isolated tests never write them, so finding one
# means the target is live (or was used without isolation): refuse to touch it.
LIVE_AUTHORITY_PATTERNS = ("caos:utu:v1:*", "caos:{genesis-sessions}:v1:*")


def disposable_utu_redis_url() -> str:
    """The verified disposable test Redis URL, or skip when none is configured."""
    url = os.environ.get(TEST_REDIS_ENV)
    if not url:
        pytest.skip(f"Set {TEST_REDIS_ENV} to a disposable Redis for UTU integration tests")
    try:
        require_disposable_redis(url, settings.cache.redis_url)
    except UnsafeVerificationTarget as exc:
        raise UnsafeVerificationTarget(
            f"{TEST_REDIS_ENV} is not a verified disposable Redis ({exc}). Use a separate "
            "disposable Redis server, never the application's configured Redis."
        ) from exc
    if has_default_route():
        raise UnsafeVerificationTarget(
            "Destructive UTU integration tests run only on the harness's internal network "
            f"(this runner can reach other networks). Run them through {HARNESS}."
        )
    declared_redis_identity()
    return url


def declared_redis_identity() -> str:
    declared = os.environ.get(TEST_REDIS_IDENTITY_ENV, "")
    if not _RUN_ID.fullmatch(declared):
        raise UnsafeVerificationTarget(
            f"{TEST_REDIS_IDENTITY_ENV} must be declared by {HARNESS} (the Redis process "
            "identity of the disposable server it created); refusing destructive tests."
        )
    return declared


def has_default_route(v4: str = "/proc/net/route", v6: str = "/proc/net/ipv6_route") -> bool:
    """True unless the kernel routing tables show no usable default route. Unreadable
    IPv4 routes count as a default route (fail closed); IPv6 reject routes on ``lo``
    (present even on internal networks) do not."""
    try:
        routes = Path(v4).read_text().splitlines()[1:]
    except OSError:
        return True
    for line in routes:
        fields = line.split()
        if len(fields) > 3 and fields[1] == "00000000" and int(fields[3], 16) & _RTF_UP:
            return True
    try:
        routes = Path(v6).read_text().splitlines()
    except OSError:
        return False  # IPv6 disabled: no IPv6 route at all
    for line in routes:
        fields = line.split()
        if (
            len(fields) >= 10
            and fields[0] == "0" * 32
            and fields[1] == "00"
            and fields[9] != "lo"
            and not int(fields[8], 16) & _RTF_REJECT
        ):
            return True
    return False


async def verify_disposable_redis(redis: Any) -> None:
    """Before any write: the connected server is the declared one, and it is clean."""
    declared = declared_redis_identity()
    try:
        actual = (await redis.info("server")).get("run_id")
    except Exception as exc:  # any failure to prove identity refuses
        raise UnsafeVerificationTarget(
            f"Cannot read the Redis process identity (INFO server): {type(exc).__name__}"
        ) from exc
    if actual != declared:
        raise UnsafeVerificationTarget(
            f"The connected Redis is not the server {HARNESS} declared "
            f"({TEST_REDIS_IDENTITY_ENV} mismatch); refusing destructive tests."
        )
    await refuse_live_authority(redis)


async def refuse_live_authority(redis: Any) -> None:
    """Refuse a test Redis that already holds production-format authority keys."""
    for pattern in LIVE_AUTHORITY_PATTERNS:
        async for _ in redis.scan_iter(match=pattern, count=100):
            raise UnsafeVerificationTarget(
                f"{TEST_REDIS_ENV} holds production-format authority keys ({pattern}); it "
                "is live or contaminated. Refusing before any test write."
            )


class IsolatedRevocationStore(RedisRevocationStore):
    """The production store with every tenant key under one test run's prefix."""

    def __init__(self, *, repository: Any, run_id: str, timeout: float = 1.0) -> None:
        super().__init__(repository=repository, timeout=timeout)
        self.prefix = f"{TEST_KEY_PREFIX}{run_id}:"

    def _key(self, tenant: str) -> str:  # type: ignore[override]
        return self.prefix + RedisRevocationStore._key(tenant)


def new_run_id() -> str:
    return uuid4().hex


def isolate_utu(container: Any, repository: Any, run_id: str) -> IsolatedRevocationStore:
    """Bind this container's UTU to the run's isolated store, before first use."""
    store = IsolatedRevocationStore(repository=repository, run_id=run_id)
    # ``utu_revocations`` is consumed only by the ``utu_authority`` singleton; rebind that
    # argument (the fixtures' established ``add_kwargs`` pattern).
    container.agentverse.utu_authority.add_kwargs(revocations=providers.Object(store))
    if container.agentverse.utu_authority()._store() is not store:
        raise RuntimeError("UTU was resolved before isolation; refusing a shared authority key")
    return store
